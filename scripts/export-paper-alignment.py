def require(condition, message):
    if not condition:
        raise ValueError(message)


def read_inputs(root):
    files = dict(INPUTS)
    for panel, (name, hashes) in PANEL_INPUTS.items():
        for filename, digest in hashes.items():
            files[f"panels/{panel}/{filename}"] = (f"{DATA}/{name}/{filename}", digest)
    blobs = {}
    for artifact, (relative, expected) in files.items():
        blob = (root / relative).read_bytes()
        require(hashlib.sha256(blob).hexdigest() == expected, "Reviewed source hash mismatch: " + artifact)
        blobs[artifact] = blob
    require(blobs["paper/figure-5.pdf"] == blobs["alignment/figure.pdf"], "Installed figure differs from approved package")
    require(blobs["paper/table-v.tex"] == blobs["alignment/table.tex"], "Installed table differs from approved package")
    return blobs, [{"id": key, "sha256": digest, "bytes": len(blobs[key])} for key, (_, digest) in files.items()]


def export(root):
    blobs, artifacts = read_inputs(root)
    parse_json = lambda name: json.loads(blobs[name])
    parse_csv = lambda name: list(csv.DictReader(io.StringIO(blobs[name].decode("utf-8"))))
    manifest = parse_json("alignment/array-manifest.json")
    metrics_rows = {r["panel"]: r for r in parse_csv("alignment/metrics.csv")}
    table_rows = parse_csv("alignment/table-data.csv")
    require(len(table_rows) == 12, "Expected eight ATE cells and four scale cells")
    evaluator = parse_json("alignment/evaluator-revision.json")["commit"]
    require(evaluator == parse_json("alignment/second-case-evaluator-revision.json")["commit"], "Evaluator revisions differ")
    panels = []
    all_arrays = {}
    for letter, (name, hashes) in PANEL_INPUTS.items():
        case = next(c for c in CASES if letter in c["panels"])
        count = case["associatedPoseCount"]
        prefix = f"panels/{letter}/"
        metrics = parse_json(prefix + "metrics.json")
        require(metrics["matched_poses"] == int(metrics_rows[name]["matched_poses"]) == count, "Pose-count mismatch: " + letter)
        require(manifest[name]["data_sha256"] == hashes["evaluation_arrays.npz"], "Array-manifest mismatch: " + letter)
        with np.load(io.BytesIO(blobs[prefix + "evaluation_arrays.npz"]), allow_pickle=False) as archive:
            require(set(archive.files) == set(ARRAY_SHAPES), "Unexpected numeric array keys: " + letter)
            arrays = {key: archive[key] for key in ARRAY_SHAPES}
        for key, shape in ARRAY_SHAPES.items():
            require(arrays[key].dtype == np.dtype("float64") and arrays[key].shape == (count,) + shape, "Array shape/type mismatch: " + letter + "/" + key)
            require(bool(np.isfinite(arrays[key]).all()), "Nonfinite stored array: " + letter + "/" + key)
        all_arrays[letter] = arrays
        top_csv = list(csv.reader(io.StringIO(blobs[prefix + "top_view.csv"].decode("utf-8"))))
        require(top_csv[0] == TOP_VIEW_COLUMNS and len(top_csv) == count + 1, "Top-view shape mismatch: " + letter)
        # Check correspondence only: metrics are copied, never recalculated.
        top_numeric = np.array(top_csv[1:], dtype=float)
        np.testing.assert_allclose(top_numeric[:, 0], arrays["gt_t"], rtol=0, atol=1e-9)
        np.testing.assert_allclose(top_numeric[:, 1:3], arrays["gt_pos"][:, :2], rtol=0, atol=1e-10)
        np.testing.assert_allclose(top_numeric[:, 3:5], arrays["est_pos"][:, :2], rtol=0, atol=1e-10)
        rows = {r["metric"]: r for r in table_rows if r["panel"] == letter}
        require(set(rows) == {"position_ate_m", "rotation_ate_deg", "scale"}, "Table metric identity mismatch: " + letter)
        for r in rows.values():
            require(r["source_panel"] == name and r["system"] == case["system"] and r["mode"] == case["mode"] and int(r["matched_poses"]) == count, "Table case identity mismatch: " + letter)
            require(r["sample_scope"] == "all associated poses; no trimming", "Unexpected sample scope")
        values = {}
        for key, unit in [("position_ate_m", "m"), ("rotation_ate_deg", "deg")]:
            row = rows[key]
            require(metrics[key] == float(row["source_value"]) == float(metrics_rows[name][key]), "Source metric mismatch: " + letter + "/" + key)
            require(row["displayed_value"] == f"{metrics[key]:.3f}", "Source display precision mismatch")
            values[key] = {"value": metrics[key], "valueText": row["source_value"], "displayText": row["displayed_value"], "unit": unit, "state": row["display_status"]}
        scale_row = rows["scale"]
        scale_value = float(scale_row["source_value"]) if scale_row["source_value"] else None
        require(metrics.get("scale") == scale_value, "Scale state/value mismatch: " + letter)
        scale = {"value": scale_value, "valueText": scale_row["source_value"] or None, "displayText": scale_row["displayed_value"] or "—", "state": scale_row["display_status"], "fitted": scale_row["display_status"] == "fitted_scale"}
        if scale["fitted"]:
            require(scale["displayText"] == "0.001302" and scale_value == 0.0013016088998384326, "Unexpected fitted scale")
        record_file = "alignment.json" if letter in ("a", "b") else "transform.json"
        alignment = parse_json(prefix + record_file)
        panels.append({
            "id": letter, "caseId": case["id"], "sourcePanelId": name,
            "alignment": rows["position_ate_m"]["alignment"], "associatedPoseCount": count,
            "positionATE": values["position_ate_m"], "orientationATE": values["rotation_ate_deg"], "scale": scale,
            "alignmentRecord": {"sourceArtifactId": prefix + record_file, "data": alignment},
            "associatedSamples": {"sourceArtifactId": prefix + "evaluation_arrays.npz", "arrays": {key: value.tolist() for key, value in arrays.items()}},
            "topView": {"sourceArtifactId": prefix + "top_view.csv", "columns": TOP_VIEW_COLUMNS, "rows": top_csv[1:], "precision": "Original CSV value strings, without rounding or row selection."},
            "sourceArtifactIds": [prefix + filename for filename in hashes],
        })
    for left, right in [("a", "b"), ("c", "d")]:
        for key in ("gt_t", "gt_pos", "gt_quat"):
            require(np.array_equal(all_arrays[left][key], all_arrays[right][key]), "Paired reference samples differ: " + key)
    for label, key in [("Position ATE (m)", "positionATE"), ("Orientation ATE (deg)", "orientationATE")]:
        line = next(s for s in blobs["paper/table-v.tex"].decode().splitlines() if s.startswith(label + " &"))
        tokens = [s.strip() for s in line.split("&")[1:]]
        tokens[-1] = tokens[-1].removesuffix("\\\\").strip()
        require(tokens == [p[key]["displayText"] for p in panels], "Installed table column/value mismatch")
    result = {
        "schemaVersion": 1,
        "id": "paper-alignment-comparisons",
        "paper": {"snapshotRevision": PAPER_REVISION, "figure": "5", "table": "V", "figureLabel": "fig:alignment-comparison", "tableLabel": "tab:alignment-results"},
        "protocol": {"scope": "All associated poses, without trimming.", "metric": "ATE RMSE", "positionUnit": "m", "orientationUnit": "deg", "benchmarkDriftValidAggregation": False, "metricsRecomputedDuringExport": False, "pairing": "Each pair preserves identical associated reference timestamps, positions and orientations.", "comparisonLimit": "The VINS-Fusion comparison changes rotation fitting and scale fitting; it is not a scale-only comparison."},
        "figure": {"path": "images/results/paper-alignment.svg", "sourceArtifactId": "alignment/figure.svg", "sha256": INPUTS["alignment/figure.svg"][1], "widthMm": 177.8, "heightMm": 44.0, "viewBox": [0, 0, 504, 124.724409], "caption": "Reference positions are teal and solid; estimates are orange and dashed. Circles and crosses mark starts and ends. All panels preserve equal X/Y spatial scaling. Panels (a,b) share a viewing range; (c,d) have separate ranges in meters."},
        "cases": CASES, "panels": panels,
        "provenance": {"lineage": "The installed paper figure PDF is byte-identical to the approved figure-package PDF; the displayed SVG is copied byte-for-byte from that same package. The installed table is byte-identical to its preserved table body. Table values, display precision, scales, counts and arrays are copied from hash-verified inputs.", "artifactIdScope": "Neutral relative identifiers for frozen input artifacts; not filesystem paths or public download URLs.", "evaluatorRevisionRecordedBySource": evaluator, "sourceArtifacts": artifacts},
        "limitations": ["The saved arrays are already associated and aligned. This export does not rerun the evaluator or reconstruct raw timestamp association.", "The arrays retain their source field names and quaternion component ordering; no pose-convention conversion is performed.", "A dash denotes scale was not fitted. Source panels a/b omit scale; panel c explicitly records fixed scale 1.0; panel d records a fitted scale.", "These comparison values are separate from the benchmark's drift-valid ATE/RPE aggregates."]
    }
    encoded = (json.dumps(result, indent=2, ensure_ascii=False, allow_nan=False) + "\n").encode("utf-8")
    for forbidden in [b"/Users/", b"/home/", b"/mnt/", b"file://", b"http://", b"https://", b"yxpeng", b"cchen"]:
        require(forbidden not in encoded, "Private path or external identity in public JSON")
    return encoded, blobs["alignment/figure.svg"]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--paper-root", required=True, type=Path)
    parser.add_argument("--output-root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--check", action="store_true", help="Verify existing output bytes without writing")
    args = parser.parse_args()
    data, svg = export(args.paper_root.resolve())
    outputs = [("public/data/current-paper-alignment.json", data), ("public/images/results/paper-alignment.svg", svg)]
    for relative, blob in outputs:
        destination = args.output_root.resolve() / relative
        if args.check:
            require(destination.is_file() and destination.read_bytes() == blob, "Installed export differs: " + relative)
        else:
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_bytes(blob)
    print("Verified" if args.check else "Exported", "four alignment panels, eight unchanged ATE values, 499/440 associated poses, and the approved SVG.")


if __name__ == "__main__":
    main()
